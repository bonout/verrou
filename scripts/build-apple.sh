#!/usr/bin/env bash
# Builds the Rust core for the Apple apps and generates the Swift binding.
#
#   scripts/build-apple.sh                    # macOS only, release, arm64 + x86_64
#   PROFILE=debug scripts/build-apple.sh
#   PLATFORMS=ios scripts/build-apple.sh      # iPhone (device + simulator) only
#   PLATFORMS=all scripts/build-apple.sh      # macOS + iPhone, in the same xcframework
#
# Variables:
#   PLATFORMS    macos (default, what install-macos.sh expects), ios or all
#   TARGETS      macOS targets (default: aarch64-apple-darwin x86_64-apple-darwin)
#   IOS_TARGETS  iPhone targets (default: aarch64-apple-ios; empty: no device
#                slice, for a faster simulator build)
#   SIM_TARGETS  simulator targets (default: aarch64-apple-ios-sim; add
#                x86_64-apple-ios for a simulator on an Intel Mac)
#
# Produces:
#   apple/Frameworks/VerrouFFI.xcframework   verrou_ffiFFI.framework, a dynamic
#                                            framework (library, C headers,
#                                            module), one slice per platform:
#                                            embedded once in each app, the
#                                            AutoFill extension loads the app's
#   apple/Shared/Generated/verrou_ffi.swift  Swift binding generated by UniFFI
#   apple/Helpers/verrou-native-host         Native Messaging host (macOS only)
#   apple/Helpers/verrou                     command line tool (macOS only)
#
# An `ios` build alone replaces the xcframework without a macOS slice: the
# Mac app no longer compiles until `macos` or `all` is run again.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
PROFILE="${PROFILE:-release}"
PLATFORMS="${PLATFORMS:-macos}"
case "$PLATFORMS" in
  macos) BUILD_MAC=1; BUILD_IOS=0 ;;
  ios) BUILD_MAC=0; BUILD_IOS=1 ;;
  all) BUILD_MAC=1; BUILD_IOS=1 ;;
  *) echo "unknown PLATFORMS: $PLATFORMS (macos, ios or all)" >&2; exit 2 ;;
esac
# Same targets as the apps (apple/project.yml): without them, the
# dependencies' assembly code is compiled for the machine's OS version.
export MACOSX_DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-15.0}"
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-17.0}"
read -r -a MAC_TARGETS <<< "${TARGETS:-aarch64-apple-darwin x86_64-apple-darwin}"
read -r -a IOS_DEVICE_TARGETS <<< "${IOS_TARGETS-aarch64-apple-ios}"
read -r -a IOS_SIM_TARGETS <<< "${SIM_TARGETS:-aarch64-apple-ios-sim}"
FLAG=$([[ "$PROFILE" == release ]] && echo "--release" || echo "")
OUT="$ROOT/apple/Frameworks"
GEN="$ROOT/apple/Shared/Generated"
TMP="$ROOT/target/apple"

FRAMEWORK=verrou_ffiFFI
VERSION="$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -1)"

build_lib() {
  rustup target add "$1" >/dev/null 2>&1 || true
  cargo rustc -p verrou-ffi --lib $FLAG --target "$1" --crate-type cdylib \
    -- -C link-arg=-Wl,-headerpad_max_install_names
}

framework() {
  local dest="$1/$FRAMEWORK.framework" platform="$2"; shift 2
  local libs=() base id plist
  for target in "$@"; do libs+=("target/$target/$PROFILE/libverrou_ffi.dylib"); done
  rm -rf "$dest"
  if [[ "$platform" == MacOSX ]]; then
    base="$dest/Versions/A"
    mkdir -p "$base/Headers" "$base/Modules" "$base/Resources"
    ln -s A "$dest/Versions/Current"
    for entry in Headers Modules Resources "$FRAMEWORK"; do ln -s "Versions/Current/$entry" "$dest/$entry"; done
    id="@rpath/$FRAMEWORK.framework/Versions/A/$FRAMEWORK"
    plist="$base/Resources/Info.plist"
  else
    base="$dest"
    mkdir -p "$base/Headers" "$base/Modules"
    id="@rpath/$FRAMEWORK.framework/$FRAMEWORK"
    plist="$base/Info.plist"
  fi
  lipo -create "${libs[@]}" -output "$base/$FRAMEWORK"
  install_name_tool -id "$id" "$base/$FRAMEWORK"
  cp "$TMP/include/$FRAMEWORK.h" "$base/Headers/"
  printf 'framework module %s {\n  umbrella header "%s.h"\n  export *\n  module * { export * }\n}\n' \
    "$FRAMEWORK" "$FRAMEWORK" > "$base/Modules/module.modulemap"
  local minimum=(MinimumOSVersion "$IPHONEOS_DEPLOYMENT_TARGET")
  [[ "$platform" == MacOSX ]] && minimum=(LSMinimumSystemVersion "$MACOSX_DEPLOYMENT_TARGET")
  cat > "$plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>$FRAMEWORK</string>
  <key>CFBundleIdentifier</key><string>app.verrou.ffi</string>
  <key>CFBundleName</key><string>$FRAMEWORK</string>
  <key>CFBundlePackageType</key><string>FMWK</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>CFBundleSupportedPlatforms</key><array><string>$platform</string></array>
  <key>${minimum[0]}</key><string>${minimum[1]}</string>
</dict>
</plist>
PLIST
  XC_ARGS+=(-framework "$dest")
}

rm -rf "$TMP" && mkdir -p "$TMP/include" "$GEN" "$OUT"
XC_ARGS=()
BINDGEN_LIB=""

if [[ $BUILD_MAC == 1 ]]; then
  for target in "${MAC_TARGETS[@]}"; do
    build_lib "$target"
    cargo build -p verrou-bridge --bin verrou-native-host $FLAG --target "$target"
    cargo build -p verrou-cli --bin verrou $FLAG --target "$target"
  done
  HOSTS=()
  for target in "${MAC_TARGETS[@]}"; do HOSTS+=("target/$target/$PROFILE/verrou-native-host"); done
  mkdir -p "$ROOT/apple/Helpers"
  lipo -create "${HOSTS[@]}" -output "$ROOT/apple/Helpers/verrou-native-host"
  CLIS=()
  for target in "${MAC_TARGETS[@]}"; do CLIS+=("target/$target/$PROFILE/verrou"); done
  lipo -create "${CLIS[@]}" -output "$ROOT/apple/Helpers/verrou"
  BINDGEN_LIB="target/${MAC_TARGETS[0]}/$PROFILE/libverrou_ffi.dylib"
fi

if [[ $BUILD_IOS == 1 ]]; then
  for target in ${IOS_DEVICE_TARGETS[@]+"${IOS_DEVICE_TARGETS[@]}"} "${IOS_SIM_TARGETS[@]}"; do
    build_lib "$target"
  done
  BINDGEN_LIB="${BINDGEN_LIB:-target/${IOS_SIM_TARGETS[0]}/$PROFILE/libverrou_ffi.dylib}"
fi

# The binding is generated from an already built dynamic library, which
# carries the UniFFI metadata (identical on all platforms).
cargo run -q -p verrou-ffi --bin uniffi-bindgen -- generate \
  --library "$BINDGEN_LIB" --language swift --out-dir "$TMP/swift"
cp "$TMP/swift/verrou_ffi.swift" "$GEN/verrou_ffi.swift"
cp "$TMP/swift/verrou_ffiFFI.h" "$TMP/include/"

[[ $BUILD_MAC == 1 ]] && framework "$TMP/macos" MacOSX "${MAC_TARGETS[@]}"
if [[ $BUILD_IOS == 1 ]]; then
  if [[ ${#IOS_DEVICE_TARGETS[@]} -gt 0 ]]; then
    framework "$TMP/ios" iPhoneOS "${IOS_DEVICE_TARGETS[@]}"
  fi
  framework "$TMP/ios-simulator" iPhoneSimulator "${IOS_SIM_TARGETS[@]}"
fi

rm -rf "$OUT/VerrouFFI.xcframework"
xcodebuild -create-xcframework "${XC_ARGS[@]}" \
  -output "$OUT/VerrouFFI.xcframework" >/dev/null
echo "OK ($PLATFORMS): $OUT/VerrouFFI.xcframework, $GEN/verrou_ffi.swift"
